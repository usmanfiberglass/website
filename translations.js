function changeLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');

        // 1. Capture original English text if not already captured
        // This ensures that we always have the English version available to revert to
        if (!el.hasAttribute('data-original-text')) {
            el.setAttribute('data-original-text', el.innerHTML);
        }

        if (lang === 'ur') {
            if (translations.ur[key]) {
                el.innerHTML = translations.ur[key];
            }
        } else {
            // Revert to English (original HTML content)
            if (el.hasAttribute('data-original-text')) {
                el.innerHTML = el.getAttribute('data-original-text');
            }
        }
    });

    const body = document.body;
    if (lang === 'ur') {
        body.setAttribute('dir', 'rtl');
        body.classList.add('lang-ur');
    } else {
        body.setAttribute('dir', 'ltr');
        body.classList.remove('lang-ur');
    }

    // Save preference
    localStorage.setItem('preferredLanguage', lang);
}

document.addEventListener('DOMContentLoaded', () => {
    // initialize original text immediately
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        if (!el.hasAttribute('data-original-text')) {
            el.setAttribute('data-original-text', el.innerHTML);
        }
    });

    const savedLang = localStorage.getItem('preferredLanguage') || 'en';
    changeLanguage(savedLang);

    const langBtn = document.getElementById('langToggle');
    if (langBtn) {
        langBtn.addEventListener('click', () => {
            const currentLang = document.body.getAttribute('dir') === 'rtl' ? 'ur' : 'en';
            const newLang = currentLang === 'en' ? 'ur' : 'en';
            changeLanguage(newLang);
            langBtn.textContent = newLang === 'en' ? 'اردو' : 'English';
        });
        // Set initial button text
        langBtn.textContent = savedLang === 'en' ? 'اردو' : 'English';
    }
});
